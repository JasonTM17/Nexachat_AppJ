package com.nexachat.core.ui;

import com.nexachat.summary.CitationResolver;
import com.nexachat.summary.SummaryResponse;
import com.nexachat.summary.SummaryScope;
import com.nexachat.summary.SummaryUiState;
import com.nexachat.summary.UnreadBannerRule;
import java.util.Objects;
import java.util.Set;

/**
 * Pure Java decision and presentation rules for the conversation catch-up summary UI.
 */
public final class SummaryUiRules {

    private SummaryUiRules() { }

    /**
     * Determines whether the unread summary banner should be displayed.
     * The banner is shown when unread count is >= {@link UnreadBannerRule#MIN_UNREAD_COUNT}
     * unless the user previously dismissed the banner for this exact unread sequence window.
     * If newer messages arrive (lastSeq > dismissedForSeq), the banner re-appears.
     *
     * @param unreadCount number of unread messages in conversation
     * @param dismissedForSeq sequence number of the latest message when dismissed, or null
     * @param currentLastSeq current latest message sequence number
     * @return true if banner should be rendered
     */
    public static boolean shouldShowBanner(int unreadCount, Long dismissedForSeq, long currentLastSeq) {
        if (unreadCount < UnreadBannerRule.MIN_UNREAD_COUNT) {
            return false;
        }
        if (dismissedForSeq == null) {
            return true;
        }
        return currentLastSeq > dismissedForSeq;
    }

    /**
     * Identifies whether the summary was produced by an external generative LLM or on-device local engine.
     *
     * @param generatedBy string returned by backend ("LLM" or "LOCAL")
     * @return true if generated by external LLM
     */
    public static boolean isLlmGenerated(String generatedBy) {
        return "LLM".equalsIgnoreCase(generatedBy);
    }

    /** An engine badge is meaningful only after a summary names its engine. */
    public static boolean shouldShowEngineBadge(String generatedBy) {
        return generatedBy != null && !generatedBy.trim().isEmpty();
    }

    /**
     * Process death keeps the summary id but drops the in-memory body.
     * IDLE plus a saved id is a cache miss, not a fresh request still in flight.
     */
    public static boolean restoredSummaryMissing(SummaryUiState.Status status, String lastSummaryId) {
        return status == SummaryUiState.Status.IDLE
                && lastSummaryId != null
                && !lastSummaryId.trim().isEmpty();
    }

    /**
     * Checks if a cited message ID can be jumped to in the current loaded message list.
     *
     * @param messageId cited message UUID
     * @param localMessageIds set of currently available message IDs in memory
     * @return true if message can be jumped to
     */
    public static boolean isCitationJumpable(String messageId, Set<String> localMessageIds) {
        if (messageId == null || localMessageIds == null) {
            return false;
        }
        String resolved = CitationResolver.resolve(messageId, localMessageIds);
        return !CitationResolver.UNAVAILABLE.equals(resolved);
    }

    /**
     * Determines whether summary copy/share actions should be enabled.
     *
     * @param status current UI state status
     * @param summary response body
     * @return true if content exists to be copied or shared
     */
    public static boolean canShareOrCopy(SummaryUiState.Status status, SummaryResponse summary) {
        if (status != SummaryUiState.Status.READY || summary == null) {
            return false;
        }
        boolean hasOverview = !summary.getOverview().trim().isEmpty();
        boolean hasKeyPoints = !summary.getKeyPoints().isEmpty();
        boolean hasDecisions = !summary.getDecisions().isEmpty();
        boolean hasActionItems = !summary.getActionItems().isEmpty();
        return hasOverview || hasKeyPoints || hasDecisions || hasActionItems;
    }

    /** Enabled state for summary sheet footer actions derived from presentation flags. */
    public static final class FooterButtonState {
        public final boolean regenerateEnabled;
        public final boolean copyEnabled;
        public final boolean shareEnabled;

        FooterButtonState(boolean regenerateEnabled, boolean copyEnabled, boolean shareEnabled) {
            this.regenerateEnabled = regenerateEnabled;
            this.copyEnabled = copyEnabled;
            this.shareEnabled = shareEnabled;
        }
    }

    public static FooterButtonState footerButtonState(
            boolean loading,
            boolean error,
            SummaryUiState.Status status,
            SummaryResponse summary
    ) {
        if (loading) {
            return new FooterButtonState(false, false, false);
        }
        if (error) {
            return new FooterButtonState(true, false, false);
        }
        boolean canAct = canShareOrCopy(status, summary);
        return new FooterButtonState(true, canAct, canAct);
    }

    /**
     * Returns string resource name for the given summary scope chip.
     */
    public static String getScopeResourceName(SummaryScope scope) {
        Objects.requireNonNull(scope, "scope");
        switch (scope) {
            case UNREAD:
                return "summary_scope_unread";
            case LAST_N:
                return "summary_scope_last_n";
            case TODAY:
                return "summary_scope_today";
            default:
                throw new IllegalArgumentException("Unknown scope: " + scope);
        }
    }
}
