package com.nexachat.core.storage;

import android.security.keystore.KeyGenParameterSpec;
import android.security.keystore.KeyProperties;
import java.io.IOException;
import java.security.GeneralSecurityException;
import java.security.KeyStore;
import java.util.Arrays;
import javax.crypto.Cipher;
import javax.crypto.KeyGenerator;
import javax.crypto.SecretKey;
import javax.crypto.spec.GCMParameterSpec;
import javax.inject.Inject;
import kotlin.Pair;

/**
 * AES/GCM cipher whose key lives in AndroidKeyStore.
 *
 * <p>The key is generated once with alias {@link #KEY_ALIAS} and never leaves the
 * (hardware-backed, where available) keystore — only ciphertext is ever returned.
 * GCM also authenticates the ciphertext, so tampered prefs fail {@code doFinal}
 * instead of decrypting to garbage.
 *
 * <p>Wire format: {@code IV (12 bytes) || ciphertext+tag}. A fresh random 12-byte IV
 * is generated by {@link Cipher} per encryption and prepended to the output — GCM
 * must never reuse an IV under one key.
 */
public final class AesGcmTokenCipher implements TokenCipher {

    private static final String ANDROID_KEYSTORE = "AndroidKeyStore";
    private static final int KEY_SIZE_BITS = 256;

    public static final String KEY_ALIAS = "NexaChatTokenKey";
    public static final String TRANSFORMATION = "AES/GCM/NoPadding";
    public static final int IV_LENGTH = 12;
    public static final int GCM_TAG_BITS = 128;

    private final KeyStore keyStore;

    @Inject
    public AesGcmTokenCipher() {
        try {
            KeyStore ks = KeyStore.getInstance(ANDROID_KEYSTORE);
            ks.load(null);
            this.keyStore = ks;
        } catch (GeneralSecurityException | IOException e) {
            throw new IllegalStateException(e);
        }
    }

    private SecretKey secretKey() throws GeneralSecurityException, IOException {
        KeyStore.Entry entry = keyStore.getEntry(KEY_ALIAS, null);
        if (entry instanceof KeyStore.SecretKeyEntry) {
            return ((KeyStore.SecretKeyEntry) entry).getSecretKey();
        }
        return generateKey();
    }

    private SecretKey generateKey() throws GeneralSecurityException {
        KeyGenerator generator =
                KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEYSTORE);
        KeyGenParameterSpec spec =
                new KeyGenParameterSpec.Builder(
                                KEY_ALIAS,
                                KeyProperties.PURPOSE_ENCRYPT | KeyProperties.PURPOSE_DECRYPT)
                        .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                        .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                        .setKeySize(KEY_SIZE_BITS)
                        .setUserAuthenticationRequired(false)
                        .build();
        generator.init(spec);
        return generator.generateKey();
    }

    @Override
    public byte[] encrypt(byte[] plaintext) throws GeneralSecurityException, IOException {
        Cipher cipher = Cipher.getInstance(TRANSFORMATION);
        cipher.init(Cipher.ENCRYPT_MODE, secretKey());
        byte[] ciphertext = cipher.doFinal(plaintext);
        return packGcm(cipher.getIV(), ciphertext);
    }

    @Override
    public byte[] decrypt(byte[] packed) throws GeneralSecurityException, IOException {
        Pair<byte[], byte[]> ivAndCiphertext = unpackGcm(packed);
        byte[] iv = ivAndCiphertext.getFirst();
        byte[] ciphertext = ivAndCiphertext.getSecond();
        Cipher cipher = Cipher.getInstance(TRANSFORMATION);
        cipher.init(Cipher.DECRYPT_MODE, secretKey(), new GCMParameterSpec(GCM_TAG_BITS, iv));
        return cipher.doFinal(ciphertext);
    }

    /**
     * Concatenates {@code iv || ciphertext}. {@code iv} must be exactly {@link #IV_LENGTH}
     * bytes (the GCM standard). Public static so JVM unit tests can exercise the framing
     * without loading KeyStore classes.
     */
    public static byte[] packGcm(byte[] iv, byte[] ciphertext) {
        if (iv.length != IV_LENGTH) {
            throw new IllegalArgumentException(
                    "GCM IV must be " + IV_LENGTH + " bytes, got " + iv.length);
        }
        byte[] out = new byte[iv.length + ciphertext.length];
        System.arraycopy(iv, 0, out, 0, iv.length);
        System.arraycopy(ciphertext, 0, out, iv.length, ciphertext.length);
        return out;
    }

    /** Splits a {@link #packGcm} blob back into {@code (iv, ciphertext)}. */
    public static Pair<byte[], byte[]> unpackGcm(byte[] packed) {
        if (packed.length <= IV_LENGTH) {
            throw new IllegalArgumentException("Packed token too short: " + packed.length + " bytes");
        }
        byte[] iv = Arrays.copyOfRange(packed, 0, IV_LENGTH);
        byte[] ciphertext = Arrays.copyOfRange(packed, IV_LENGTH, packed.length);
        return new Pair<>(iv, ciphertext);
    }
}
