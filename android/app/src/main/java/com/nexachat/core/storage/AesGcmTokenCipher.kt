package com.nexachat.core.storage

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec
import javax.inject.Inject

/**
 * AES/GCM cipher whose key lives in AndroidKeyStore.
 *
 * The key is generated once with alias [AesGcmTokenCipher.KEY_ALIAS] and never
 * leaves the (hardware-backed, where available) keystore — only ciphertext is
 * ever returned. GCM also authenticates the ciphertext, so tampered prefs fail
 * `doFinal` instead of decrypting to garbage.
 *
 * Wire format: `IV (12 bytes) || ciphertext+tag`. A fresh random 12-byte IV is
 * generated by [Cipher] per encryption and prepended to the output — GCM must
 * never reuse an IV under one key.
 */
class AesGcmTokenCipher @Inject constructor() : TokenCipher {

    private val keyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }

    private val secretKey: SecretKey
        get() = (keyStore.getEntry(KEY_ALIAS, null) as? KeyStore.SecretKeyEntry)?.secretKey
            ?: generateKey()

    private fun generateKey(): SecretKey {
        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEYSTORE)
        generator.init(
            KeyGenParameterSpec.Builder(
                KEY_ALIAS,
                KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
            )
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(KEY_SIZE_BITS)
                .setUserAuthenticationRequired(false)
                .build(),
        )
        return generator.generateKey()
    }

    override fun encrypt(plaintext: ByteArray): ByteArray {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, secretKey)
        val ciphertext = cipher.doFinal(plaintext)
        return packGcm(cipher.iv, ciphertext)
    }

    override fun decrypt(packed: ByteArray): ByteArray {
        val (iv, ciphertext) = unpackGcm(packed)
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, secretKey, GCMParameterSpec(GCM_TAG_BITS, iv))
        return cipher.doFinal(ciphertext)
    }

    companion object {
        const val KEY_ALIAS = "NexaChatTokenKey"
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val IV_LENGTH = 12
        const val GCM_TAG_BITS = 128
        private const val ANDROID_KEYSTORE = "AndroidKeyStore"
        private const val KEY_SIZE_BITS = 256
    }
}

/**
 * Concatenates `iv || ciphertext`. [iv] must be exactly
 * [AesGcmTokenCipher.IV_LENGTH] bytes (the GCM standard). Internal + top-level
 * so JVM unit tests can exercise the framing without loading KeyStore classes.
 */
internal fun packGcm(iv: ByteArray, ciphertext: ByteArray): ByteArray {
    require(iv.size == AesGcmTokenCipher.IV_LENGTH) {
        "GCM IV must be ${AesGcmTokenCipher.IV_LENGTH} bytes, got ${iv.size}"
    }
    return ByteArray(iv.size + ciphertext.size).also { out ->
        iv.copyInto(out, destinationOffset = 0)
        ciphertext.copyInto(out, destinationOffset = iv.size)
    }
}

/** Splits a [packGcm] blob back into `(iv, ciphertext)`. */
internal fun unpackGcm(packed: ByteArray): Pair<ByteArray, ByteArray> {
    require(packed.size > AesGcmTokenCipher.IV_LENGTH) {
        "Packed token too short: ${packed.size} bytes"
    }
    return packed.copyOfRange(0, AesGcmTokenCipher.IV_LENGTH) to
        packed.copyOfRange(AesGcmTokenCipher.IV_LENGTH, packed.size)
}
