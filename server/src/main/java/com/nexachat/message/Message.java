package com.nexachat.message;

import com.nexachat.conversation.Conversation;
import com.nexachat.user.User;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.time.Instant;
import java.util.UUID;

/**
 * Maps {@code messages} (V1__init.sql).
 *
 * <p>Sequencing model (plan §9.3.1): {@code seq} is a GLOBAL {@code BIGSERIAL} —
 * assigned by the database sequence at INSERT, monotonic forever, independent of
 * any clock. Ordering inside a conversation is therefore just {@code seq DESC};
 * cursor pagination is {@code seq < :beforeSeq}. Gaps are expected and harmless
 * (rollbacks and interleaved conversations share the one sequence).
 *
 * <p>Inserts do NOT go through {@code EntityManager.persist} in the hot path:
 * {@link MessageRepository#insertIgnoringDuplicateKey} issues the
 * {@code INSERT ... ON CONFLICT (sender_id, client_message_id) DO NOTHING} that
 * makes retries race-safe at the DB level (plan §9.3.2). The entity remains the
 * read/relationship model (sender display name, reply lookup).
 */
@Entity
@Table(name = "messages")
public class Message {

    /** {@code VARCHAR(7) CHECK (type IN ('TEXT','IMAGE','VIDEO','AUDIO','FILE','SYSTEM'))}. */
    public enum Type {
        TEXT,
        IMAGE,
        VIDEO,
        AUDIO,
        FILE,
        SYSTEM
    }

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    @Column(name = "id", nullable = false, updatable = false)
    private UUID id;

    /**
     * Global ordering sequence; generated by the {@code messages_seq_seq}
     * BIGSERIAL at INSERT. Not {@code @GeneratedValue}: Hibernate only allows
     * that on identifiers. Inserts use the native
     * {@code INSERT ... ON CONFLICT DO NOTHING} in {@code MessageRepository},
     * so the entity only ever reads this column back.
     */
    @Column(name = "seq", nullable = false, insertable = false, updatable = false)
    private Long seq;

    /** LAZY per plan §9.3.7 — message list reads use {@code MessageRow} projections. */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "conversation_id", nullable = false)
    private Conversation conversation;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "sender_id", nullable = false)
    private User sender;

    /** Idempotency key minted by the client; UNIQUE with sender_id in DDL. */
    @Column(name = "client_message_id", nullable = false, updatable = false)
    private UUID clientMessageId;

    @Enumerated(EnumType.STRING)
    @Column(name = "type", nullable = false, length = 7)
    private Type type;

    /** Nullable: media-only messages carry attachments, not text. */
    @Column(name = "content")
    private String content;

    /** Nullable self-reference: the message this one replies to (creative feature). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "reply_to_id")
    private Message replyTo;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @Column(name = "edited_at")
    private Instant editedAt;

    @Column(name = "deleted_at")
    private Instant deletedAt;

    protected Message() {
        // JPA only
    }

    public UUID getId() {
        return id;
    }

    public Long getSeq() {
        return seq;
    }

    public Conversation getConversation() {
        return conversation;
    }

    public User getSender() {
        return sender;
    }

    public UUID getClientMessageId() {
        return clientMessageId;
    }

    public Type getType() {
        return type;
    }

    public String getContent() {
        return content;
    }

    public Message getReplyTo() {
        return replyTo;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public Instant getEditedAt() {
        return editedAt;
    }

    public Instant getDeletedAt() {
        return deletedAt;
    }

    public void editContent(String content, Instant editedAt) {
        this.content = content;
        this.editedAt = editedAt;
    }

    public void softDelete(Instant deletedAt) {
        this.content = null;
        this.deletedAt = deletedAt;
    }
}
